#!/usr/bin/env python3
"""Generate an EmbeddedImage lookup from explicit encoded image files."""
import argparse
import json
from pathlib import Path
import re


MIME_TYPES = {
    ".png": "image/png",
    ".webp": "image/webp",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".gif": "image/gif",
    ".avif": "image/avif",
    ".svg": "image/svg+xml",
    ".ico": "image/vnd.microsoft.icon",
}


def generate(root, files, namespace, function, header):
    identifier = r"[A-Za-z_][A-Za-z_0-9]*"
    if not re.fullmatch(identifier + r"(?:::" + identifier + r")*", namespace):
        raise ValueError("invalid C++ namespace")
    if not re.fullmatch(identifier, function):
        raise ValueError("invalid C++ function name")
    if not header or any(c in header for c in '\"\n\r\\'):
        raise ValueError("invalid C++ header path")
    root = root.resolve()
    images = {}
    for file in files:
        path = (root / file).resolve()
        key = path.relative_to(root).as_posix()
        if key in images:
            raise ValueError("duplicate image key: " + key)
        mime = MIME_TYPES.get(path.suffix.lower())
        if mime is None:
            raise ValueError("unsupported image extension: " + key)
        data = path.read_bytes()
        if not data:
            raise ValueError("empty image: " + key)
        images[key] = (data, mime)

    lines = [
        "// Generated by embed_images.py; do not edit.",
        '#include "' + header + '"',
        '#include "aniparse/media/ImageResource.hpp"',
        "#include <array>",
        "#include <optional>",
        "#include <span>",
        "#include <string_view>",
        "",
        "namespace " + namespace + " {",
        "namespace {",
    ]
    entries = []
    bytes_per_line = 24
    for index, (key, (data, mime)) in enumerate(sorted(images.items())):
        name = "image_" + str(index)
        lines.append("constexpr unsigned char " + name + "[] = {")
        for offset in range(0, len(data), bytes_per_line):
            lines.append("    " + ", ".join(str(b) for b in data[offset:offset + bytes_per_line]) + ",")
        lines.append("};")
        entries.append("    Entry{" + json.dumps(key, ensure_ascii=False) + ", "
                       + name + ", " + str(len(data)) + ", " + json.dumps(mime) + "},")
    lines += [
        "struct Entry {",
        "    std::string_view key;",
        "    const unsigned char* data;",
        "    std::size_t size;",
        "    std::string_view mime_type;",
        "};",
        "constexpr std::array<Entry, " + str(len(entries)) + "> images = {{",
        *entries,
        "}};",
        "} // namespace",
        "",
        "std::optional<aniparse::EmbeddedImage> " + function + "(std::string_view key) {",
        "    for (const auto& image : images) {",
        "        if (image.key == key) {",
        "            return aniparse::EmbeddedImage{",
        "                std::as_bytes(std::span{image.data, image.size}), image.mime_type};",
        "        }",
        "    }",
        "    return std::nullopt;",
        "}",
        "} // namespace " + namespace,
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--namespace", required=True)
    parser.add_argument("--function", required=True)
    parser.add_argument("--header", required=True)
    parser.add_argument("--files", required=True, nargs="+")
    args = parser.parse_args()
    try:
        source = generate(args.root, args.files, args.namespace, args.function, args.header)
    except (ValueError, OSError) as error:
        parser.error(str(error))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(source, encoding="utf-8")


if __name__ == "__main__":
    main()
